interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  language: "es",
  setLanguage: () => {},
  t: (text) => text,
});

function isLanguage(value: string | null): value is Language {
  return value === "es" || value === "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("es");

  useEffect(() => {
    try {
      const savedLanguage = localStorage.getItem("tempo-language");
      if (isLanguage(savedLanguage)) {
        window.setTimeout(() => setLanguageState(savedLanguage), 0);
      }
    } catch {
      // Language changes still work for the current session if storage is unavailable.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "es" ? "es" : "en";
  }, [language]);

  function setLanguage(nextLanguage: Language) {
    setLanguageState(nextLanguage);
    try {
      localStorage.setItem("tempo-language", nextLanguage);
    } catch {
      // Keep the selected language active for the current session.
    }
  }

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (text) => language === "en" ? englishTranslations[text] ?? text : text,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
